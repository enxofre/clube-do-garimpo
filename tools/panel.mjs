#!/usr/bin/env node
// Local admin panel (no dependencies). Run: node tools/panel.mjs  ->  http://127.0.0.1:4173
// Lets a non-developer refresh Shopee products, add Amazon products and publish the site.
import { createServer } from "node:http";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parseCsv, parseMoney, findColumns } from "./csv.mjs";

const run = promisify(execFile);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const PORT = 4173;
const dataFile = join(root, "data", "amazon.json");
const csvFile = join(root, "feeds", "amazon.csv");
const manualFile = join(root, "data", "manual.json");
const manualCsv = join(root, "feeds", "manual.csv");
// Sales/commissions are private: stored with the GarimpoBot app data, never inside the (public) site repo.
const appData = join(process.env.LOCALAPPDATA ?? join(process.env.HOME ?? root, ".local", "share"), "GarimpoBot", "clube-do-garimpo");
const salesFile = join(appData, "sales.json");
const couponsFile = join(root, "data", "coupons.json");
const readCoupons = () => readJson(couponsFile, []);
function writeCoupons(list) {
  mkdirSync(dirname(couponsFile), { recursive: true });
  writeFileSync(couponsFile, JSON.stringify(list, null, 2));
  writeFileSync(join(root, "coupons.js"), "// Generated by tools/panel.mjs. Do not edit by hand.\nwindow.COUPONS = " + JSON.stringify(list, null, 2) + ";\n");
}

// ---- Coupon collection (Promobit public coupons page, via tools/fetch-coupons.mjs)
// Coupon links must pay the storefront owner, not the aggregator: each store maps to the owner's own link.
const STORE_LINKS = {
  amazon: "https://www.amazon.com.br/?tag=clubedogari05-20",
  shopee: "https://collshp.com/deborasmagnus644?view=storefront",
  mercadolivre: "https://www.mercadolivre.com.br/social/scandolaradebora20220711142326/lists?matt_tool=85651324",
};
const STORE_OF = { "mercadolivre.com.br": "mercadolivre", "amazon.com.br": "amazon", "shopee.com.br": "shopee", "magazineluiza.com.br": "magalu" };

// Instructions text usually states the expiry ("... até às 23h59 do dia 28/12/26 ...").
function expiryOf(text) {
  const all = [...String(text ?? "").matchAll(/(\d{2})\/(\d{2})\/(\d{2,4})/g)];
  const m = all.at(-1);
  if (!m) return "";
  const year = m[3].length === 2 ? `20${m[3]}` : m[3];
  return `${year}-${m[2]}-${m[1]}`;
}

async function syncCoupons() {
  const scraped = await step(() => node("tools/fetch-coupons.mjs"));
  if (!scraped.ok) return scraped;
  const raw = readJson(join(root, "data", "promobit-coupons.json"), []);
  const today = new Date().toISOString().slice(0, 10);
  const imported = raw
    .filter(c => c.coupon_status_name === "APPROVED" && c.coupon_code)
    .map(c => {
      const store = STORE_OF[String(c.store_domain ?? "").replace(/^www\./, "")] ?? "outros";
      const domain = /^[a-z0-9.-]+$/i.test(c.store_domain ?? "") ? `https://${c.store_domain}/` : "";
      return {
        store, code: clean(c.coupon_code, 40).replace(/\s+/g, "").toUpperCase(),
        description: clean(`${c.coupon_discount_short ?? ""} ${c.coupon_discount_on ?? c.store_name ?? ""}${(String(c.coupon_title ?? "").match(/OFF\s+(acima de.*)$/i) ?? [])[1] ? " — " + String(c.coupon_title).match(/OFF\s+(acima de.*)$/i)[1] : ""}`, 160),
        url: STORE_LINKS[store] ?? domain, validUntil: expiryOf(c.coupon_instructions), source: "promobit",
        storeName: clean(c.store_name, 40),
      };
    })
    .filter(c => c.code && c.url && (!c.validUntil || c.validUntil >= today))
    .filter((c, i, all) => all.findIndex(o => o.storeName === c.storeName && o.code === c.code) === i);
  // Coupons added by hand are kept; only the collected ones are replaced.
  writeCoupons([...readCoupons().filter(c => c.source !== "promobit"), ...imported]);
  return { ok: true, log: `${imported.length} cupons reais importados (códigos ativos, do Promobit).` };
}

const readJson = (file, fallback) => (existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : fallback);
const readAmazon = () => readJson(dataFile, []);
const readManual = () => readJson(manualFile, []);
const readSales = () => readJson(salesFile, []);

function writeManual(list) {
  mkdirSync(dirname(manualFile), { recursive: true });
  mkdirSync(dirname(manualCsv), { recursive: true });
  writeFileSync(manualFile, JSON.stringify(list, null, 2));
  const q = v => `"${String(v ?? "").replace(/"/g, '""')}"`;
  writeFileSync(manualCsv, "name;price;original_price;image_link;product_link;category\n" +
    list.map(p => [p.title, String(p.price).replace(".", ","), p.oldPrice ? String(p.oldPrice).replace(".", ",") : "", p.image, p.url, p.category].map(q).join(";")).join("\n") + (list.length ? "\n" : ""));
}

const SALES_ALIASES = {
  date: ["date", "data", "ordertime", "horadopedido", "datadopedido", "purchasedate", "datadacompra", "dataehora", "orderdate"],
  product: ["product", "produto", "itemname", "nomedoitem", "nomedoproduto", "title", "item", "nomedoproduto"],
  orderValue: ["ordervalue", "valordopedido", "valordacompra", "purchaseamount", "saleamount", "valordavenda", "itemprice", "valor", "precodoitem", "revenue"],
  commission: ["commission", "comissao", "comissaoliquida", "netcommission", "totalcommission", "comissaototal", "ganhos", "earnings", "comissaoestimada", "valordacomissao", "advertisingfees", "taxasdepublicidade"],
  status: ["status", "orderstatus", "statusdopedido", "situacao"],
};

function importSales(store, text) {
  const rows = parseCsv(text);
  if (rows.length < 2) throw new Error("O arquivo está vazio.");
  const col = findColumns(rows[0], SALES_ALIASES);
  if (col.commission === undefined) throw new Error(`Não achei a coluna de comissão. Cabeçalhos do arquivo: ${rows[0].join(" | ")}`);
  const parsed = rows.slice(1).map(r => ({
    store,
    date: col.date !== undefined ? String(r[col.date] ?? "").slice(0, 25) : "",
    product: col.product !== undefined ? String(r[col.product] ?? "").slice(0, 140) : "",
    orderValue: col.orderValue !== undefined ? parseMoney(r[col.orderValue]) || 0 : 0,
    commission: parseMoney(r[col.commission]) || 0,
    status: col.status !== undefined ? String(r[col.status] ?? "").slice(0, 40) : "",
  })).filter(s => s.commission > 0 || s.orderValue > 0);
  // Re-importing a report replaces that store's previous rows.
  const all = [...readSales().filter(s => s.store !== store), ...parsed];
  mkdirSync(dirname(salesFile), { recursive: true });
  writeFileSync(salesFile, JSON.stringify(all, null, 2));
  return parsed.length;
}
function writeAmazon(list) {
  mkdirSync(dirname(dataFile), { recursive: true });
  mkdirSync(dirname(csvFile), { recursive: true });
  writeFileSync(dataFile, JSON.stringify(list, null, 2));
  const q = v => `"${String(v ?? "").replace(/"/g, '""')}"`;
  writeFileSync(csvFile, "asin;title;category;image\n" + list.map(p => [p.asin, p.title, p.category, p.image].map(q).join(";")).join("\n") + (list.length ? "\n" : ""));
}

const clean = (v, max) => String(v ?? "").replace(/[\r\n\t;]+/g, " ").trim().slice(0, max);
const node = (...args) => run(process.execPath, args, { cwd: root, timeout: 300000 });
const git = (...args) => run("git", args, { cwd: root, timeout: 120000 });

async function step(fn) {
  try { const r = await fn(); return { ok: true, log: `${r.stdout}${r.stderr}`.trim() }; }
  catch (e) { return { ok: false, log: `${e.stdout ?? ""}${e.stderr ?? ""}${e.message}`.trim() }; }
}

async function refreshAndBuild() {
  const fetched = await step(() => node("tools/fetch-collshp.mjs"));
  if (!fetched.ok) return fetched;
  const built = await step(() => node("tools/build-products.mjs", "--min-discount", "0", "--limit", "300"));
  return { ok: built.ok, log: `${fetched.log}\n${built.log}` };
}

async function publish() {
  const status = await git("status", "--porcelain");
  if (!status.stdout.trim()) return { ok: true, log: "Nada novo para publicar." };
  const stamp = new Date().toLocaleString("pt-BR");
  const out = await step(async () => {
    await git("add", "-A");
    await git("commit", "-m", `Atualiza ofertas (${stamp})`);
    return git("push");
  });
  return out.ok ? { ok: true, log: "Publicado! O site atualiza em 1 a 2 minutos." } : out;
}

const json = (res, code, body) => { res.writeHead(code, { "Content-Type": "application/json; charset=utf-8" }); res.end(JSON.stringify(body)); };
const body = (req, max = 20000) => new Promise(resolve => { let d = ""; req.on("data", c => { d += c; if (d.length > max) req.destroy(); }); req.on("end", () => { try { resolve(JSON.parse(d || "{}")); } catch { resolve({}); } }); });
const rebuild = () => step(() => node("tools/build-products.mjs", "--min-discount", "0", "--limit", "300"));

const server = createServer(async (req, res) => {
  // Loopback + custom header on writes blocks DNS rebinding and cross-site requests.
  if (!/^(127\.0\.0\.1|localhost):4173$/.test(req.headers.host ?? "")) return json(res, 403, { error: "host" });
  const url = new URL(req.url, "http://x");
  if (req.method === "GET" && url.pathname === "/") {
    res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
    return res.end(readFileSync(join(root, "tools", "panel.html")));
  }
  if (req.method === "GET" && url.pathname === "/assets/logo.jpg") {
    res.writeHead(200, { "Content-Type": "image/jpeg" });
    return res.end(readFileSync(join(root, "assets", "logo.jpg")));
  }
  if (req.method !== "GET" && req.headers["x-panel"] !== "1") return json(res, 403, { error: "header" });

  if (req.method === "GET" && url.pathname === "/api/state") {
    const products = existsSync(join(root, "products.js")) ? (readFileSync(join(root, "products.js"), "utf8").match(/"url":/g) ?? []).length : 0;
    const dirty = (await git("status", "--porcelain").catch(() => ({ stdout: "" }))).stdout.trim().length > 0;
    return json(res, 200, { products, dirty, amazon: readAmazon(), manual: readManual(), coupons: readCoupons() });
  }
  if (req.method === "POST" && url.pathname === "/api/coupons/sync") {
    try { return json(res, 200, await syncCoupons()); } catch (e) { return json(res, 200, { ok: false, log: e.message }); }
  }
  if (req.method === "POST" && url.pathname === "/api/coupons") {
    const b = await body(req);
    let link = "";
    try { const u = new URL(String(b.url ?? "").trim()); if (u.protocol === "https:") link = u.href; } catch { /* invalid */ }
    const code = clean(b.code, 40).replace(/\s+/g, "").toUpperCase();
    const validUntil = /^\d{4}-\d{2}-\d{2}$/.test(String(b.validUntil ?? "")) ? b.validUntil : "";
    const store = ["shopee", "amazon", "mercadolivre", "magalu", "outros"].includes(b.store) ? b.store : "outros";
    if (!link || !code) return json(res, 400, { ok: false, log: "Informe o código do cupom e o link (https) da loja." });
    const list = readCoupons().filter(c => !(c.store === store && c.code === code));
    list.push({ store, code, description: clean(b.description, 160), url: link, validUntil });
    writeCoupons(list);
    return json(res, 200, { ok: true, log: `Cupom ${code} salvo.` });
  }
  if (req.method === "DELETE" && url.pathname === "/api/coupons") {
    const [store, code] = [url.searchParams.get("store"), url.searchParams.get("code")];
    writeCoupons(readCoupons().filter(c => !(c.store === store && c.code === code)));
    return json(res, 200, { ok: true, log: "Cupom removido." });
  }
  if (req.method === "GET" && url.pathname === "/api/sales") return json(res, 200, readSales());
  if (req.method === "POST" && url.pathname === "/api/sales") {
    const b = await body(req, 3_000_000);
    const store = ["shopee", "amazon", "mercadolivre", "outras"].includes(b.store) ? b.store : "outras";
    try { return json(res, 200, { ok: true, log: `${importSales(store, String(b.csv ?? ""))} vendas importadas.` }); }
    catch (e) { return json(res, 400, { ok: false, log: e.message }); }
  }
  if (req.method === "DELETE" && url.pathname.startsWith("/api/sales/")) {
    const store = url.pathname.split("/").pop();
    mkdirSync(dirname(salesFile), { recursive: true });
    writeFileSync(salesFile, JSON.stringify(readSales().filter(s => s.store !== store), null, 2));
    return json(res, 200, { ok: true, log: "Vendas removidas." });
  }
  if (req.method === "POST" && url.pathname === "/api/manual") {
    const b = await body(req);
    let link = "";
    try { const u = new URL(String(b.url ?? "").trim()); if (u.protocol === "https:") link = u.href; } catch { /* invalid */ }
    const title = clean(b.title, 140);
    const price = parseMoney(b.price);
    const old = parseMoney(b.oldPrice);
    if (!link || !title || !(price > 0)) return json(res, 400, { ok: false, log: "Informe o link (https), o nome e o preço." });
    let image = clean(b.image, 500);
    try { if (image && new URL(image).protocol !== "https:") image = ""; } catch { image = ""; }
    const list = readManual().filter(p => p.url !== link);
    list.push({ title, url: link, price, oldPrice: old > price ? old : null, image, category: clean(b.category, 40) || "Outros" });
    writeManual(list);
    return json(res, 200, await rebuild());
  }
  if (req.method === "DELETE" && url.pathname === "/api/manual") {
    writeManual(readManual().filter(p => p.url !== url.searchParams.get("url")));
    return json(res, 200, await rebuild());
  }
  if (req.method === "POST" && url.pathname === "/api/shopee") return json(res, 200, await refreshAndBuild());
  if (req.method === "POST" && url.pathname === "/api/amazon") {
    const b = await body(req);
    const asin = clean(b.asin, 10).toUpperCase();
    const title = clean(b.title, 140);
    if (!/^[A-Z0-9]{10}$/.test(asin) || !title) return json(res, 400, { ok: false, log: "Informe o ASIN (10 caracteres) e o título." });
    let image = clean(b.image, 500);
    try { if (image && new URL(image).protocol !== "https:") image = ""; } catch { image = ""; }
    const list = readAmazon().filter(p => p.asin !== asin);
    list.push({ asin, title, category: clean(b.category, 40) || "Outros", image });
    writeAmazon(list);
    return json(res, 200, await step(() => node("tools/build-products.mjs", "--min-discount", "0", "--limit", "300")));
  }
  if (req.method === "DELETE" && url.pathname.startsWith("/api/amazon/")) {
    writeAmazon(readAmazon().filter(p => p.asin !== url.pathname.split("/").pop()));
    return json(res, 200, await step(() => node("tools/build-products.mjs", "--min-discount", "0", "--limit", "300")));
  }
  if (req.method === "POST" && url.pathname === "/api/publish") return json(res, 200, await publish());
  json(res, 404, { error: "not found" });
});

server.listen(PORT, "127.0.0.1", () => console.log(`Painel do Clube do Garimpo em http://127.0.0.1:${PORT}  (Ctrl+C para fechar)`));
